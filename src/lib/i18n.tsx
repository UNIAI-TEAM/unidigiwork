export type Key = keyof (typeof dict)["vi"];

type PartialDict = Partial<Record<Key, string>>;
const extraDicts: Record<"my" | "km" | "lo" | "id" | "ms", PartialDict> = {
  my: my as PartialDict,
  km: km as PartialDict,
  lo: lo as PartialDict,
  id: id as PartialDict,
  ms: ms as PartialDict,
};

export const LANGS: { code: Lang; label: string; short: string }[] = [
  { code: "vi", label: "Tiếng Việt", short: "VI" },
  { code: "en", label: "English", short: "EN" },
  { code: "my", label: "မြန်မာ (Myanmar)", short: "MY" },
  { code: "km", label: "ភាសាខ្មែរ (Khmer)", short: "KM" },
  { code: "lo", label: "ພາສາລາວ (Lao)", short: "LO" },
  { code: "id", label: "Bahasa Indonesia", short: "ID" },
  { code: "ms", label: "Bahasa Melayu", short: "MS" },
];
const LANG_CODES = LANGS.map((l) => l.code);

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }>({
  lang: "vi",
  setLang: () => {},
  t: (k) => k as string,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("vi");

  useEffect(() => {
    const saved = (typeof localStorage !== "undefined" &&
      localStorage.getItem("uniwork-lang")) as Lang | null;
    if (saved && LANG_CODES.includes(saved)) setLangState(saved);
    // Ngôn ngữ do quản trị viên đặt (lưu trong hồ sơ) được ưu tiên.
    let cancelled = false;
    void (async () => {
      try {
        const { supabase } = await import("@/integrations/supabase/client");
        const { data: auth } = await supabase.auth.getUser();
        if (!auth.user) return;
        const { data } = await supabase
          .from("user_ui_prefs")
          .select("lang")
          .eq("user_id", auth.user.id)
          .maybeSingle();
        const remote = (data as { lang?: string } | null)?.lang as Lang | undefined;
        if (!cancelled && remote && LANG_CODES.includes(remote)) {
          setLangState(remote);
          try {
            localStorage.setItem("uniwork-lang", remote);
          } catch {
            /* ignore */
          }
        }
      } catch {
        /* ignore */
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("uniwork-lang", l);
    } catch {
      /* ignore */
    }
    void (async () => {
      try {
        const { supabase } = await import("@/integrations/supabase/client");
        const { data: auth } = await supabase.auth.getUser();
        if (!auth.user) return;
        await supabase
          .from("user_ui_prefs")
          .upsert({ user_id: auth.user.id, lang: l }, { onConflict: "user_id" });
      } catch {
        /* ignore */
      }
    })();
    if (typeof document !== "undefined") document.documentElement.lang = l;
  };

  const t = (k: Key) => {
    if (lang === "vi" || lang === "en") {
      return (
        (dict[lang] as Record<string, string>)[k] ?? (dict.vi as Record<string, string>)[k] ?? k
      );
    }
    return (
      extraDicts[lang][k] ??
      (dict.en as Record<string, string>)[k] ??
      (dict.vi as Record<string, string>)[k] ??
      (k as string)
    );
  };

  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useI18n = () => useContext(LangCtx);

/** BCP-47 tag cho định dạng ngày/giờ theo ngôn ngữ đang chọn. */
export const localeTag = (lang: Lang): string =>
  ({ vi: "vi-VN", en: "en-US", my: "my-MM", km: "km-KH", lo: "lo-LA", id: "id-ID", ms: "ms-MY" })[
    lang
  ] ?? "vi-VN";

export function LanguageToggle({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();
  const [open, setOpen] = useState(false);
  const current = LANGS.find((l) => l.code === lang) ?? LANGS[0];
  return (
    <div className={`relative ${className}`}>
      <button
        onClick={() => setOpen((v) => !v)}
        aria-label="Chọn ngôn ngữ"
        aria-haspopup="menu"
        aria-expanded={open}
        title={current.label}
        className="flex items-center gap-1 rounded-lg p-2 text-xs font-medium uppercase text-muted-foreground hover:bg-surface-2 hover:text-foreground focus-visible:ring-1 focus-visible:ring-ring"
      >
        <Globe className="h-4 w-4" />
        {current.short}
      </button>
      {open ? (
        <>
          <div className="fixed inset-0 z-40" onClick={() => setOpen(false)} aria-hidden />
          <div
            role="menu"
            className="absolute right-0 z-50 mt-1 w-48 overflow-hidden rounded-xl border border-border bg-popover p-1 shadow-md"
          >
            {LANGS.map((l) => (
              <button
                key={l.code}
                role="menuitem"
                onClick={() => {
                  setLang(l.code);
                  setOpen(false);
                }}
                className={`flex w-full items-center justify-between rounded-lg px-3 py-2 text-left text-sm transition-colors hover:bg-surface-2 ${
                  l.code === lang ? "text-foreground" : "text-muted-foreground"
                }`}
              >
                <span>{l.label}</span>
                <span className="text-xs uppercase">{l.short}</span>
              </button>
            ))}
          </div>
        </>
      ) : null}
    </div>
  );
}
